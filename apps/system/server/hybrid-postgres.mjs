import pg from 'pg';
import { capturePostgresSnapshot, verifyPostgresSnapshot } from './hybrid-backup.mjs';

const identifier = name => '"' + name.replaceAll('"', '""') + '"';
export const runtimeSchema = value => {
    if (!/^fama_(system|control)_runtime$/.test(value || '')) throw new Error('Esquema privado da aplicação inválido.');
    return value;
};

// Keep placeholders and quoted aliases intact. Never interpolate bound values.
export function postgresSql(input) {
    let sql = '', quote = '', parameter = 0;
    for (let index = 0; index < input.length; index++) {
        const char = input[index], next = input[index + 1];
        if (quote) {
            if (char === quote && next === quote) { sql += char + next; index++; continue; }
            if (char === quote) { sql += quote === '`' ? '"' : char; quote = ''; }
            else sql += char;
            continue;
        }
        if (char === '-' && next === '-') { const end = input.indexOf('\n', index); if (end < 0) break; sql += input.slice(index, end + 1); index = end; continue; }
        if (char === '/' && next === '*') { const end = input.indexOf('*/', index + 2); if (end < 0) throw new Error('Comentário SQL incompleto.'); sql += input.slice(index, end + 2); index = end + 1; continue; }
        if (['\'', '"', '`'].includes(char)) { quote = char; sql += char === '`' ? '"' : char; }
        else sql += char === '?' ? '$' + (++parameter) : char;
    }
    const literals=[];
    sql=sql.replace(/'(?:''|[^'])*'|"(?:""|[^"])*"|--[^\n]*|\/\*[\s\S]*?\*\//g,value=>{const index=literals.push(value)-1;return '\u0001'+index+'\u0002';});
    sql = sql.replace(/\bAS\s+([a-z_][A-Za-z0-9_]*)\b/g, (match, name) => /[A-Z]/.test(name) ? 'AS ' + identifier(name) : match);
    if (/^\s*INSERT\s+OR\s+IGNORE\s+/i.test(sql)) {
        sql = sql.replace(/INSERT\s+OR\s+IGNORE/i, 'INSERT').trim().replace(/;$/, '') + ' ON CONFLICT DO NOTHING';
    }
    if (/^\s*(CREATE|ALTER)\b/i.test(sql)) {
        sql = sql.replace(/\binteger\s+DEFAULT\s+true\b/gi, 'integer DEFAULT 1').replace(/\binteger\s+DEFAULT\s+false\b/gi, 'integer DEFAULT 0').replace(/\breal\b/gi, 'double precision');
        sql = sql.replace(/\binteger\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi, 'integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
        // SQLite stores these affinity types as strings; keep the imported bytes.
        sql = sql.replace(/\b(?:TIMESTAMP|DATETIME|DATE)\b/gi, 'text');
    }
    sql=sql.replace(/\bjson_(object|set|valid)\s*\(/gi, (_match, name) => 'fama_json_' + name.toLowerCase() + '(');
    return sql.replace(/\u0001(\d+)\u0002/g,(_match,index)=>literals[Number(index)]);
}

export function postgresPool(configuration) {
    const url = new URL(configuration.FAMA_POSTGRES_URL || '');
    if (!['postgres:', 'postgresql:'].includes(url.protocol)) throw new Error('Configure a conexão PostgreSQL privada.');
    for (const key of ['sslmode', 'sslcert', 'sslkey', 'sslrootcert']) url.searchParams.delete(key);
    return new pg.Pool({ connectionString: url.href, max: 2, connectionTimeoutMillis: 15000,
        idleTimeoutMillis: 15000, ssl: { rejectUnauthorized: true, ...(configuration.FAMA_POSTGRES_CA ? { ca: configuration.FAMA_POSTGRES_CA } : {}) } });
}

class Statement {
    constructor(database, sql, values = []) { Object.assign(this, { database, sql, values }); }
    bind(...values) { return new Statement(this.database, this.sql, values.map(value => value === undefined ? null : typeof value === 'boolean' ? Number(value) : value)); }
    async all() { return this.database.execute(this); }
    async run() { return this.all(); }
    async first(column) { const row = (await this.all()).results[0]; return row ? column === undefined ? row : row[column] : null; }
    async raw({ columnNames = false } = {}) {
        const result = await this.all();
        const columns = result.columns;
        const rows = result.results.map(row => columns.map(name => row[name]));
        return columnNames ? [columns, ...rows] : rows;
    }
}

export class HybridPostgres {
    constructor(pool, schema) { this.pool = pool; this.schema = runtimeSchema(schema); }
    prepare(sql) { return new Statement(this, sql); }
    async transaction(action) {
        const client = await this.pool.connect();
        try {
            await client.query('BEGIN');
            await client.query('SET LOCAL search_path TO ' + identifier(this.schema) + ', pg_catalog');
            await client.query("SET LOCAL statement_timeout = '25s'");
            const result = await action(client);
            await client.query('COMMIT');
            return result;
        } catch (error) { await client.query('ROLLBACK').catch(() => {}); throw error; }
        finally { client.release(); }
    }
    async execute(statement, client) {
        if (!client) return this.transaction(connection => this.execute(statement, connection));
        const started = performance.now();
        let sql = statement.sql;
        const tableInfo = sql.match(/^\s*PRAGMA\s+table_info\(\s*["`]?([a-z_][a-z0-9_]*)["`]?\s*\)\s*;?$/i);
        let values = statement.values;
        if (tableInfo) {
            sql = `SELECT (a.attnum-1)::integer AS cid, a.attname AS name, format_type(a.atttypid,a.atttypmod) AS type,
                a.attnotnull::integer AS "notnull", pg_get_expr(d.adbin,d.adrelid) AS dflt_value,
                COALESCE(array_position(i.indkey::smallint[],a.attnum)+1,0)::integer AS pk
                FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid JOIN pg_namespace n ON n.oid=c.relnamespace
                LEFT JOIN pg_attrdef d ON d.adrelid=c.oid AND d.adnum=a.attnum
                LEFT JOIN pg_index i ON i.indrelid=c.oid AND i.indisprimary
                WHERE n.nspname=$1 AND c.relname=$2 AND a.attnum>0 AND NOT a.attisdropped ORDER BY a.attnum`;
            values = [this.schema, tableInfo[1]];
        } else if (/^\s*PRAGMA\s+optimize\s*;?$/i.test(sql)) return { success: true, results: [], columns: [], meta: { changes: 0 } };
        else if (/^\s*PRAGMA\b|\bsqlite_schema\b|\bsqlite_master\b/i.test(sql)) {
            throw new Error('Esta operação SQLite exige o fluxo de backup PostgreSQL no modo híbrido.');
        } else sql = postgresSql(sql);
        const result = await client.query(sql, values);
        const columns = (result.fields || []).map(field => field.name);
        return { success: true, results: result.rows || [], columns, meta: {
            changes: ['INSERT', 'UPDATE', 'DELETE'].includes(result.command) ? result.rowCount : 0,
            duration: performance.now() - started,
        } };
    }
    async batch(statements) {
        if (statements.some(statement => !(statement instanceof Statement) || statement.database !== this)) throw new Error('Lote SQL inválido.');
        return this.transaction(async client => {
            const results = [];
            for (const statement of statements) results.push(await this.execute(statement, client));
            return results;
        });
    }
    async exec(sql) { return this.transaction(async client => { await client.query(postgresSql(sql)); return { count: 0, duration: 0 }; }); }
    async check() {
        const result = await this.transaction(client => client.query("SELECT to_regclass($1) AS state", [this.schema + '._fama_runtime_state']));
        if (!result.rows[0]?.state) throw new Error('Importe e valide o banco atual antes de iniciar o modo híbrido.');
    }
    async captureSnapshot() { return capturePostgresSnapshot(this); }
    async verifySnapshot(snapshot) { return verifyPostgresSnapshot(this, snapshot); }
    async close() { await this.pool.end(); }
}
